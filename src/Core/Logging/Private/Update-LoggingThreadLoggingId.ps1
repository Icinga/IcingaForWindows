<#
.SYNOPSIS
Set or renew the current per-thread logging identifier.

.DESCRIPTION
`Update-LoggingThreadLoggingId` assigns a unique logging GUID for tracing logs
generated by a thread. If a `ThreadId` is provided it is used; otherwise a new GUID is created.

.PARAMETER ThreadId
| Name | Type | Description | Default |
|------|------|-------------|---------|
| ThreadId | System.String | Optional GUID to use as the current logging id | $null |

.OUTPUTS
None — Updates `(Get-GlobalRuntimeVariable).Private.Logging.CurrentLoggingId`.

.EXAMPLE
PS> Update-LoggingThreadLoggingId -ThreadId (New-Guid).ToString()

.NOTES
This id helps correlate logs produced during the lifetime of a thread.
#>
function Update-LoggingThreadLoggingId()
{
    param (
        [string]$ThreadId = $null
    );

    # If we have no ThreadId, create a unique id for logging purposes
    # This id is renewed for every thread cycle to ensure proper tracing of logs from start to end
    if ([string]::IsNullOrEmpty($ThreadId)) {
        (Get-GlobalRuntimeVariable).Private.Logging.CurrentLoggingId = New-Guid;
    } else {
        # Once we create a new thread, make sure we can trace all logs from the start of the thread
        # until the first cycle of the thread is reached. This will ensure we can track everything
        # the thread did from it's creation to the first cycle properly
        (Get-GlobalRuntimeVariable).Private.Logging.CurrentLoggingId = $ThreadId;
    }  
}
